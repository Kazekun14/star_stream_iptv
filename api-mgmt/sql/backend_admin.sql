BEGIN
  DECLARE v_id BIGINT UNSIGNED;

  SELECT id INTO v_id
    FROM vod_tags
   WHERE name = p_name
   LIMIT 1;

  IF v_id IS NULL THEN
    INSERT INTO vod_tags(name) VALUES (p_name);
    SET v_id = LAST_INSERT_ID();
  END IF;

  SELECT 1 AS ok, v_id AS id;
END $$

