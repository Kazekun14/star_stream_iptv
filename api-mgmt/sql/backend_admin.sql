CREATE PROCEDURE sp_admin_session_revoke(IN p_session_id CHAR(64))
BEGIN
  UPDATE admin_sessions
     SET is_revoked = 1
   WHERE session_id = p_session_id;

  SELECT 1 AS ok, ROW_COUNT() AS affected;
END $$

