-- ---------------------------------------------------------
DROP PROCEDURE IF EXISTS sp_admin_login_fetch $$
CREATE PROCEDURE sp_admin_login_fetch(IN p_username VARCHAR(64))
BEGIN
  SELECT id, username, password_hash, status, must_change_password
    FROM admin_users
   WHERE username = p_username
   LIMIT 1;
END $$

