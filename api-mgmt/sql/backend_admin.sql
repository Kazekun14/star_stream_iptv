-- Replace all tags for a VOD using CSV tag IDs: "1,3,6"
DROP PROCEDURE IF EXISTS sp_vod_tags_set_csv $$
CREATE PROCEDURE sp_vod_tags_set_csv(IN p_vod_id BIGINT UNSIGNED, IN p_tag_ids_csv TEXT)
BEGIN
  DECLARE v_pos INT DEFAULT 1;
  DECLARE v_next INT DEFAULT 0;
  DECLARE v_token VARCHAR(32);
  DECLARE v_id BIGINT UNSIGNED;

  START TRANSACTION;

  DELETE FROM vod_tag_map WHERE vod_id = p_vod_id;

  IF p_tag_ids_csv IS NOT NULL AND TRIM(p_tag_ids_csv) <> '' THEN
    SET p_tag_ids_csv = CONCAT(TRIM(BOTH ',' FROM p_tag_ids_csv), ',');

    read_loop: LOOP
      SET v_next = LOCATE(',', p_tag_ids_csv, v_pos);
      IF v_next = 0 THEN
        LEAVE read_loop;
      END IF;

      SET v_token = TRIM(SUBSTRING(p_tag_ids_csv, v_pos, v_next - v_pos));
      SET v_pos = v_next + 1;

      IF v_token <> '' THEN
        SET v_id = CAST(v_token AS UNSIGNED);
        INSERT IGNORE INTO vod_tag_map(vod_id, tag_id)
        VALUES (p_vod_id, v_id);
      END IF;
    END LOOP;
  END IF;

  COMMIT;

  SELECT 1 AS ok;
END $$

