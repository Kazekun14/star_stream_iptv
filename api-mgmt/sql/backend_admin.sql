-- Replace full set using CSV IDs: "2,3,4"
DROP PROCEDURE IF EXISTS sp_package_channels_set_csv $$
CREATE PROCEDURE sp_package_channels_set_csv(IN p_package_id INT UNSIGNED, IN p_channel_ids_csv TEXT)
BEGIN
  DECLARE v_pos INT DEFAULT 1;
  DECLARE v_next INT DEFAULT 0;
  DECLARE v_token VARCHAR(32);
  DECLARE v_id INT UNSIGNED;

  START TRANSACTION;

  DELETE FROM package_channels WHERE package_id = p_package_id;

  IF p_channel_ids_csv IS NOT NULL AND TRIM(p_channel_ids_csv) <> '' THEN
    SET p_channel_ids_csv = CONCAT(TRIM(BOTH ',' FROM p_channel_ids_csv), ',');

    read_loop: LOOP
      SET v_next = LOCATE(',', p_channel_ids_csv, v_pos);
      IF v_next = 0 THEN
        LEAVE read_loop;
      END IF;

      SET v_token = TRIM(SUBSTRING(p_channel_ids_csv, v_pos, v_next - v_pos));
      SET v_pos = v_next + 1;

      IF v_token <> '' THEN
        SET v_id = CAST(v_token AS UNSIGNED);
        INSERT IGNORE INTO package_channels(package_id, channel_id)
        VALUES (p_package_id, v_id);
      END IF;
    END LOOP;
  END IF;

  COMMIT;

  SELECT 1 AS ok;
END $$


