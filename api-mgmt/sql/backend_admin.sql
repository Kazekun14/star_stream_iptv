DROP PROCEDURE IF EXISTS sp_hls_servers_list $$
CREATE PROCEDURE sp_hls_servers_list(
  IN p_status VARCHAR(16),     -- active|disabled|draining|NULL
  IN p_q VARCHAR(128),
  IN p_page INT,
  IN p_page_size INT,
  IN p_sort VARCHAR(32)        -- name_asc|name_desc|weight_desc|weight_asc|created_desc|created_asc
)
BEGIN
  DECLARE v_page INT DEFAULT GREATEST(IFNULL(p_page,1), 1);
  DECLARE v_ps   INT DEFAULT LEAST(GREATEST(IFNULL(p_page_size,50), 1), 200);
  DECLARE v_off  INT DEFAULT (v_page - 1) * v_ps;

  SELECT id, name, scheme, host, port, base_path, status, weight, created_at, updated_at,
         CONCAT(scheme, '://', host, ':', port, base_path) AS base_url
    FROM hls_servers
   WHERE (p_status IS NULL OR p_status='' OR status = p_status)
     AND (p_q IS NULL OR p_q='' OR name LIKE CONCAT('%', p_q, '%') OR host LIKE CONCAT('%', p_q, '%'))
   ORDER BY
     CASE WHEN p_sort='name_asc'     THEN name END ASC,
     CASE WHEN p_sort='name_desc'    THEN name END DESC,
     CASE WHEN p_sort='weight_asc'   THEN weight END ASC,
     CASE WHEN p_sort='weight_desc'  THEN weight END DESC,
     CASE WHEN p_sort='created_asc'  THEN created_at END ASC,
     CASE WHEN p_sort='created_desc' THEN created_at END DESC,
     id DESC
   LIMIT v_off, v_ps;

  SELECT COUNT(*) AS total
    FROM hls_servers
   WHERE (p_status IS NULL OR p_status='' OR status = p_status)
     AND (p_q IS NULL OR p_q='' OR name LIKE CONCAT('%', p_q, '%') OR host LIKE CONCAT('%', p_q, '%'));
END $$

DROP PROCEDURE IF EXISTS sp_hls_server_get $$
