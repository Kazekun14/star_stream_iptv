DROP PROCEDURE IF EXISTS sp_admin_session_validate $$
CREATE PROCEDURE sp_admin_session_validate(IN p_session_id CHAR(64), IN p_touch TINYINT)
BEGIN
  SELECT
    s.session_id,
    s.admin_id,
    s.expires_at,
    s.is_revoked,
    a.username,
    a.full_name,
    a.email,
    a.status,
    a.must_change_password
  FROM admin_sessions s
  JOIN admin_users a ON a.id = s.admin_id
  WHERE s.session_id = p_session_id
  LIMIT 1;

  IF p_touch = 1 THEN
    UPDATE admin_sessions
       SET last_seen_at = UTC_TIMESTAMP()
     WHERE session_id = p_session_id
       AND is_revoked = 0
       AND expires_at > UTC_TIMESTAMP();
  END IF;
END $$

