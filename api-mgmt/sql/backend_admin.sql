DROP PROCEDURE IF EXISTS sp_admin_audit_list $$
CREATE PROCEDURE sp_admin_audit_list(
  IN p_admin_id INT UNSIGNED,
  IN p_action VARCHAR(64),
  IN p_entity VARCHAR(64),
  IN p_from DATETIME,
  IN p_to DATETIME,
  IN p_page INT,
  IN p_page_size INT
)
BEGIN
  DECLARE v_page INT DEFAULT GREATEST(IFNULL(p_page,1), 1);
  DECLARE v_ps   INT DEFAULT LEAST(GREATEST(IFNULL(p_page_size,50), 1), 200);
  DECLARE v_off  INT DEFAULT (v_page - 1) * v_ps;

  SELECT id, admin_id, action, entity, entity_id, ip_address, user_agent, before_json, after_json, created_at
    FROM admin_audit_log
   WHERE (p_admin_id IS NULL OR admin_id = p_admin_id)
     AND (p_action IS NULL OR p_action='' OR action = p_action)
     AND (p_entity IS NULL OR p_entity='' OR entity = p_entity)
     AND (p_from IS NULL OR created_at >= p_from)
     AND (p_to IS NULL OR created_at <= p_to)
   ORDER BY created_at DESC, id DESC
   LIMIT v_off, v_ps;

  SELECT COUNT(*) AS total
    FROM admin_audit_log
   WHERE (p_admin_id IS NULL OR admin_id = p_admin_id)
     AND (p_action IS NULL OR p_action='' OR action = p_action)
     AND (p_entity IS NULL OR p_entity='' OR entity = p_entity)
     AND (p_from IS NULL OR created_at >= p_from)
     AND (p_to IS NULL OR created_at <= p_to);
END $$

