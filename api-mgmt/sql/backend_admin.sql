  IN p_session_id CHAR(64),
  IN p_admin_id INT UNSIGNED,
  IN p_ip VARCHAR(64),
  IN p_ua VARCHAR(255),
  IN p_expires_at DATETIME
)
BEGIN
  INSERT INTO admin_sessions(session_id, admin_id, ip_address, user_agent, expires_at)
  VALUES (p_session_id, p_admin_id, p_ip, p_ua, p_expires_at);

