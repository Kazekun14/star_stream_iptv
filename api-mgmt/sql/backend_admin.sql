DROP PROCEDURE IF EXISTS sp_admin_user_set_password_hash $$
CREATE PROCEDURE sp_admin_user_set_password_hash(
  IN p_id INT UNSIGNED,
  IN p_password_hash VARCHAR(255),
  IN p_must_change TINYINT
)
BEGIN
  UPDATE admin_users
     SET password_hash = p_password_hash,
         must_change_password = IFNULL(p_must_change, must_change_password)
   WHERE id = p_id;

  -- revoke all sessions on password change
  UPDATE admin_sessions
     SET is_revoked = 1
   WHERE admin_id = p_id;

  SELECT 1 AS ok, ROW_COUNT() AS affected;
END $$

